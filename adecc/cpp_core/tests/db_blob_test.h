/**
\file db_blob_test.h
\brief Generic database BLOB read/write integration tests.
\details
   Exercises the common adecc database output sink and typed result range
   against real binary columns. SQL Server additionally tests its legacy
   IMAGE column alongside VARBINARY(MAX).
*/

